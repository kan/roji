// addBackendFor registers a route pointing at the given test server URL,
// optionally under a path prefix.
func addBackendFor(t *testing.T, router *Router, hostname, serverURL string, pathPrefix ...string) {
	t.Helper()

	u, err := url.Parse(serverURL)
	if err != nil {
		t.Fatalf("parse backend URL: %v", err)
	}
	port, err := strconv.Atoi(u.Port())
	if err != nil {
		t.Fatalf("parse backend port: %v", err)
	}

	backend := &docker.Backend{
		ContainerID:   hostname,
		ContainerName: hostname,
		ServiceName:   hostname,
		Host:          u.Hostname(),
		Port:          port,
		Hostname:      hostname,
	}
	if len(pathPrefix) > 0 {
		backend.PathPrefix = pathPrefix[0]
	}
	router.AddBackend(backend)
}

// recordedRequest is what a backend received. The zero value stands for
// "no request arrived"; header.Get reads fine from a nil Header.
type recordedRequest struct {
	header http.Header
	host   string
	path   string
	// requestURI is the request line as sent, so it shows the encoding the
	// decoded path cannot: "/files/a%2Fb" against "/files/a/b".
	requestURI string
	rawQuery   string
}

// forwardedRecorder captures what a backend receives.
type forwardedRecorder struct {
	mu   sync.Mutex
	last recordedRequest
}

func (fr *forwardedRecorder) record(r *http.Request) {
	fr.mu.Lock()
	defer fr.mu.Unlock()
	fr.last = recordedRequest{
		header:     r.Header.Clone(),
		host:       r.Host,
		path:       r.URL.Path,
		requestURI: r.RequestURI,
		rawQuery:   r.URL.RawQuery,
	}
}

// get returns the last request the backend received.
func (fr *forwardedRecorder) get() recordedRequest {
	fr.mu.Lock()
	defer fr.mu.Unlock()
	return fr.last
}

// reset clears the recorder so a subtest cannot read values left by the
// previous one when a request never reaches the backend.
func (fr *forwardedRecorder) reset() {
	fr.mu.Lock()
	defer fr.mu.Unlock()
	fr.last = recordedRequest{}
}

func TestHandler_ForwardedHeaders_HTTP(t *testing.T) {
	rec := &forwardedRecorder{}
	backendServer := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		rec.record(r)
	}))
	defer backendServer.Close()

	router := NewRouter()
	addBackendFor(t, router, "xff.localhost", backendServer.URL)
	handler := NewHandler(router, nil, "roji.dev.localhost", "dev.localhost", testStatusConfig(), nil)

	tests := []struct {
		name             string
		remoteAddr       string
		spoofedForwarded string
		wantForwardedFor string
		wantRealIP       string
	}{
		{
			name:             "IPv6 client has no brackets",
			remoteAddr:       "[::1]:54321",
			wantForwardedFor: "::1",
			wantRealIP:       "::1",
		},
		{
			name:             "IPv6 global address",
			remoteAddr:       "[2001:db8::17]:443",
			wantForwardedFor: "2001:db8::17",
			wantRealIP:       "2001:db8::17",
		},
		{
			name:             "IPv4 client is forwarded once",
			remoteAddr:       "127.0.0.1:54321",
			wantForwardedFor: "127.0.0.1",
			wantRealIP:       "127.0.0.1",
		},
		{
			name:             "spoofed headers are replaced",
			remoteAddr:       "[::1]:54321",
			spoofedForwarded: "10.0.0.99",
			wantForwardedFor: "::1",
			wantRealIP:       "::1",
		},
		{
			name:             "malformed RemoteAddr is skipped",
			remoteAddr:       "not-an-address",
			wantForwardedFor: "",
			wantRealIP:       "",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			rec.reset()

			req := httptest.NewRequest("GET", "https://xff.localhost/", nil)
			req.Host = "xff.localhost"
			req.RemoteAddr = tt.remoteAddr
			if tt.spoofedForwarded != "" {
				req.Header.Set("X-Forwarded-For", tt.spoofedForwarded)
				req.Header.Set("X-Real-IP", tt.spoofedForwarded)
				// RFC 7239 equivalent, which roji never emits itself
				req.Header.Set("Forwarded", "for="+tt.spoofedForwarded+";host=evil.example;proto=http")
			}

			handler.ServeHTTP(httptest.NewRecorder(), req)

			got := rec.get()
			if v := got.header.Get("X-Forwarded-For"); v != tt.wantForwardedFor {
				t.Errorf("X-Forwarded-For = %q, want %q", v, tt.wantForwardedFor)
			}
			if v := got.header.Get("X-Real-IP"); v != tt.wantRealIP {
				t.Errorf("X-Real-IP = %q, want %q", v, tt.wantRealIP)
			}
			if v := got.header.Get("Forwarded"); v != "" {
				t.Errorf("Forwarded = %q, want it dropped", v)
			}
		})
	}
}

