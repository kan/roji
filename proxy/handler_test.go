func TestRedirectHandler(t *testing.T) {
	tests := []struct {
		name        string
		httpsPort   int
		host        string
		path        string
		expectedURL string
	}{
		{
			name:        "standard port",
			httpsPort:   443,
			host:        "api.localhost",
			path:        "/users",
			expectedURL: "https://api.localhost/users",
		},
		{
			name:        "custom port",
			httpsPort:   8443,
			host:        "api.localhost",
			path:        "/users",
			expectedURL: "https://api.localhost:8443/users",
		},
		{
			name:        "host with port",
			httpsPort:   443,
			host:        "api.localhost:80",
			path:        "/",
			expectedURL: "https://api.localhost/",
		},
		{
			name:        "IPv6 host keeps its brackets",
			httpsPort:   443,
			host:        "[::1]",
			path:        "/",
			expectedURL: "https://[::1]/",
		},
		{
			name:        "IPv6 host with port",
			httpsPort:   8443,
			host:        "[::1]:80",
			path:        "/users",
			expectedURL: "https://[::1]:8443/users",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			handler := &RedirectHandler{HTTPSPort: tt.httpsPort}

			req := httptest.NewRequest("GET", "http://"+tt.host+tt.path, nil)
			req.Host = tt.host
			w := httptest.NewRecorder()

			handler.ServeHTTP(w, req)

			if w.Code != http.StatusMovedPermanently {
				t.Errorf("status = %d, want %d", w.Code, http.StatusMovedPermanently)
			}

			location := w.Header().Get("Location")
			if location != tt.expectedURL {
				t.Errorf("Location = %q, want %q", location, tt.expectedURL)
			}
		})
	}
}

