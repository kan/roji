// TestE2E_TLSCertificateVerification verifies TLS works with generated certificates
func TestE2E_TLSCertificateVerification(t *testing.T) {
	client := testServer.httpClientWithResolver()

	// Test HTTPS connection with CA verification
	resp, err := client.Get(fmt.Sprintf("https://%s:%d/", e2eDashboardHost, e2eHTTPSPort))
	if err != nil {
		t.Fatalf("Failed to connect with TLS: %v", err)
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		t.Errorf("Status = %d, want %d", resp.StatusCode, http.StatusOK)
	}

	// Verify TLS connection details
	if resp.TLS == nil {
		t.Fatal("Expected TLS connection")
	}

	if resp.TLS.Version < tls.VersionTLS12 {
		t.Errorf("TLS version = %d, want >= TLS 1.2", resp.TLS.Version)
	}

	// Verify certificate chain
	if len(resp.TLS.PeerCertificates) == 0 {
		t.Error("No peer certificates received")
	}
}

// TestE2E_TLSCertificateRejection verifies connection fails without CA
func TestE2E_TLSCertificateRejection(t *testing.T) {
	// Create client without CA (should fail)
	client := &http.Client{
		Transport: &http.Transport{
			TLSClientConfig: &tls.Config{
				// No RootCAs - will use system pool which doesn't have our CA
			},
			DialContext: resolveHost(e2eHTTPSPort),
		},
		Timeout: 5 * time.Second,
	}

	_, err := client.Get(fmt.Sprintf("https://%s:%d/", e2eDashboardHost, e2eHTTPSPort))
	if err == nil {
		t.Error("Expected TLS verification error, but connection succeeded")
	}

	// Error should be about certificate verification
	if !strings.Contains(err.Error(), "certificate") {
		t.Logf("Got error: %v", err)
		// This is still acceptable - connection should fail
	}
}

// TestE2E_HTTPToHTTPSRedirect verifies HTTP redirects to HTTPS
func TestE2E_HTTPToHTTPSRedirect(t *testing.T) {
	client := &http.Client{
		CheckRedirect: func(req *http.Request, via []*http.Request) error {
			return http.ErrUseLastResponse
		},
		Timeout: 5 * time.Second,
	}

	resp, err := client.Get(fmt.Sprintf("http://127.0.0.1:%d/", e2eHTTPPort))
	if err != nil {
		t.Fatalf("Failed to connect: %v", err)
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusMovedPermanently {
		t.Errorf("Status = %d, want %d", resp.StatusCode, http.StatusMovedPermanently)
	}

	location := resp.Header.Get("Location")
	if !strings.HasPrefix(location, "https://") {
		t.Errorf("Location = %q, should start with https://", location)
	}

	if !strings.Contains(location, fmt.Sprintf(":%d", e2eHTTPSPort)) {
		t.Errorf("Location = %q, should contain port %d", location, e2eHTTPSPort)
	}
}

