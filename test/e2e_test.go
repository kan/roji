// TestE2E_NotFound verifies 404 handling
func TestE2E_NotFound(t *testing.T) {
	client := testServer.httpClientWithResolver()

	resp, err := client.Get(fmt.Sprintf("https://unknown.test.localhost:%d/", e2eHTTPSPort))
	if err != nil {
		t.Fatalf("Failed to make request: %v", err)
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusNotFound {
		t.Errorf("Status = %d, want %d", resp.StatusCode, http.StatusNotFound)
	}

	body, _ := io.ReadAll(resp.Body)
	if !strings.Contains(string(body), "No Route Found") {
		t.Error("404 page should contain 'No Route Found'")
	}
}
