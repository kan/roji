// TestE2E_APIEndpoints verifies API endpoints work over HTTPS
func TestE2E_APIEndpoints(t *testing.T) {
	client := testServer.httpClientWithResolver()

	endpoints := []struct {
		path       string
		wantStatus int
		checkBody  func(t *testing.T, body []byte)
	}{
		{
			path:       "/_api/health",
			wantStatus: http.StatusOK,
			checkBody: func(t *testing.T, body []byte) {
				var health map[string]interface{}
				if err := json.Unmarshal(body, &health); err != nil {
					t.Errorf("Failed to parse health response: %v", err)
					return
				}
				if health["status"] != "healthy" {
					t.Errorf("Health status = %v, want 'healthy'", health["status"])
				}
			},
		},
		{
			path:       "/_api/routes",
			wantStatus: http.StatusOK,
			checkBody: func(t *testing.T, body []byte) {
				var routes []map[string]interface{}
				if err := json.Unmarshal(body, &routes); err != nil {
					t.Errorf("Failed to parse routes response: %v", err)
					return
				}
				if len(routes) < 1 {
					t.Error("Expected at least 1 route")
				}
			},
		},
		{
			path:       "/_api/status",
			wantStatus: http.StatusOK,
			checkBody: func(t *testing.T, body []byte) {
				var status map[string]interface{}
				if err := json.Unmarshal(body, &status); err != nil {
					t.Errorf("Failed to parse status response: %v", err)
					return
				}
				if status["health"] != "healthy" && status["health"] != "degraded" {
					t.Errorf("Health = %v, want 'healthy' or 'degraded'", status["health"])
				}
			},
		},
		{
			path:       "/_api/logs",
			wantStatus: http.StatusOK,
			checkBody: func(t *testing.T, body []byte) {
				var logs []map[string]interface{}
				if err := json.Unmarshal(body, &logs); err != nil {
					t.Errorf("Failed to parse logs response: %v", err)
				}
				// Logs may be empty, that's OK
			},
		},
	}

	for _, tt := range endpoints {
		t.Run(tt.path, func(t *testing.T) {
			resp, err := client.Get(fmt.Sprintf("https://%s:%d%s", e2eDashboardHost, e2eHTTPSPort, tt.path))
			if err != nil {
				t.Fatalf("Failed to access %s: %v", tt.path, err)
			}
			defer resp.Body.Close()

			if resp.StatusCode != tt.wantStatus {
				t.Errorf("Status = %d, want %d", resp.StatusCode, tt.wantStatus)
			}

			body, _ := io.ReadAll(resp.Body)
			if tt.checkBody != nil {
				tt.checkBody(t, body)
			}
		})
	}
}

// TestE2E_SSEConnection verifies SSE connection works
func TestE2E_SSEConnection(t *testing.T) {
	client := testServer.httpClientWithResolver()

	req, err := http.NewRequest("GET", fmt.Sprintf("https://%s:%d/_api/events", e2eDashboardHost, e2eHTTPSPort), nil)
	if err != nil {
		t.Fatalf("Failed to create request: %v", err)
	}
	req.Header.Set("Accept", "text/event-stream")

	resp, err := client.Do(req)
	if err != nil {
		t.Fatalf("Failed to connect to SSE: %v", err)
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		t.Errorf("Status = %d, want %d", resp.StatusCode, http.StatusOK)
	}

	// Check SSE headers
	contentType := resp.Header.Get("Content-Type")
	if contentType != "text/event-stream" {
		t.Errorf("Content-Type = %q, want 'text/event-stream'", contentType)
	}

	// Read initial routes event
	scanner := bufio.NewScanner(resp.Body)
	var receivedEvent bool
	timeout := time.After(3 * time.Second)
	done := make(chan bool)

	go func() {
		for scanner.Scan() {
			line := scanner.Text()
			if strings.HasPrefix(line, "event: routes") {
				receivedEvent = true
				done <- true
				return
			}
		}
		done <- false
	}()

	select {
	case success := <-done:
		if !success && !receivedEvent {
			t.Error("Did not receive initial routes event")
		}
	case <-timeout:
		if !receivedEvent {
			t.Error("Timeout waiting for SSE event")
		}
	}
}

// TestE2E_SSERealtimeUpdates verifies SSE receives real-time route updates
func TestE2E_SSERealtimeUpdates(t *testing.T) {
	client := testServer.httpClientWithResolver()

	// Connect to SSE
	req, err := http.NewRequest("GET", fmt.Sprintf("https://%s:%d/_api/events", e2eDashboardHost, e2eHTTPSPort), nil)
	if err != nil {
		t.Fatalf("Failed to create request: %v", err)
	}

	resp, err := client.Do(req)
	if err != nil {
		t.Fatalf("Failed to connect to SSE: %v", err)
	}
	defer resp.Body.Close()

	// Read events in background
	var events []string
	var mu sync.Mutex
	go func() {
		scanner := bufio.NewScanner(resp.Body)
		for scanner.Scan() {
			line := scanner.Text()
			if strings.HasPrefix(line, "event:") || strings.HasPrefix(line, "data:") {
				mu.Lock()
				events = append(events, line)
				mu.Unlock()
			}
		}
	}()

	// Wait for initial event
	time.Sleep(500 * time.Millisecond)

	mu.Lock()
	initialCount := len(events)
	mu.Unlock()

	if initialCount < 2 { // event: routes + data: [...]
		t.Errorf("Expected at least 2 lines (event + data), got %d", initialCount)
	}

	// Verify the data is valid JSON
	mu.Lock()
	for _, line := range events {
		if strings.HasPrefix(line, "data:") {
			data := strings.TrimPrefix(line, "data: ")
			var routes []interface{}
			if err := json.Unmarshal([]byte(data), &routes); err != nil {
				t.Errorf("Failed to parse SSE data as JSON: %v", err)
			}
		}
	}
	mu.Unlock()
}

// TestE2E_ProxyToBackend verifies proxying to actual backend containers
func TestE2E_ProxyToBackend(t *testing.T) {
	client := testServer.httpClientWithResolver()

	// Get routes to find a valid backend
	resp, err := client.Get(fmt.Sprintf("https://%s:%d/_api/routes", e2eDashboardHost, e2eHTTPSPort))
	if err != nil {
		t.Fatalf("Failed to get routes: %v", err)
	}
	defer resp.Body.Close()

	var routes []struct {
		Hostname string `json:"hostname"`
		Target   string `json:"target"`
		Warning  string `json:"warning"`
	}
	if err := json.NewDecoder(resp.Body).Decode(&routes); err != nil {
		t.Fatalf("Failed to decode routes: %v", err)
	}

	// Find a route without warning (has valid port)
	var testHost string
	for _, r := range routes {
		if r.Warning == "" && r.Target != "" {
			testHost = r.Hostname
			break
		}
	}

	if testHost == "" {
		t.Skip("No valid backend route found for proxy test")
	}

	// Test proxy to backend
	resp, err = client.Get(fmt.Sprintf("https://%s:%d/", testHost, e2eHTTPSPort))
	if err != nil {
		t.Fatalf("Failed to proxy to %s: %v", testHost, err)
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		t.Errorf("Proxy status = %d, want %d", resp.StatusCode, http.StatusOK)
	}

	body, _ := io.ReadAll(resp.Body)
	// Should get nginx response
	if !strings.Contains(string(body), "nginx") {
		t.Errorf("Expected nginx response, got: %s", string(body)[:min(len(body), 200)])
	}
}

