func startContainers() error {
	cmd := exec.Command("docker", "compose", "-f", "docker-compose.yml", "up", "-d")
	cmd.Dir = "."
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr
	return cmd.Run()
}

func stopContainers() error {
	cmd := exec.Command("docker", "compose", "-f", "docker-compose.yml", "down", "-v")
	cmd.Dir = "."
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr
	return cmd.Run()
}

const (
	e2eNetwork      = "roji-test"
	e2eBaseDomain   = "test.localhost"
	e2eDashboardHost = "roji.test.localhost"
	e2eHTTPPort     = 18080
	e2eHTTPSPort    = 18443
)

var (
	testServer   *e2eServer
	testCertsDir string
)

type e2eServer struct {
	handler      *proxy.Handler
	router       *proxy.Router
	dockerClient *docker.Client
	httpServer   *http.Server
	httpsServer  *http.Server
	tlsConfig    *tls.Config
	clientConfig *tls.Config
}

// TestMain handles setup and teardown for E2E tests
func TestMain(m *testing.M) {
	// Start test containers
	if err := startContainers(); err != nil {
		fmt.Fprintf(os.Stderr, "Failed to start test containers: %v\n", err)
		os.Exit(1)
	}

	// Wait for containers to be ready
	time.Sleep(3 * time.Second)

	// Setup E2E server
	var err error
	testServer, err = setupE2EServer()
	if err != nil {
		fmt.Fprintf(os.Stderr, "Failed to setup E2E server: %v\n", err)
		stopContainers()
		os.Exit(1)
	}

	// Run tests
	code := m.Run()

	// Cleanup
	testServer.stop()
	stopContainers()

	// Remove temp certs dir
	if testCertsDir != "" {
		os.RemoveAll(testCertsDir)
	}

	os.Exit(code)
}

func setupE2EServer() (*e2eServer, error) {
	// Create temp directory for certificates
	var err error
	testCertsDir, err = os.MkdirTemp("", "roji-e2e-certs-*")
	if err != nil {
		return nil, fmt.Errorf("failed to create temp certs dir: %w", err)
	}

	// Generate certificates
	gen := certgen.NewGenerator(testCertsDir, e2eBaseDomain)
	if err := gen.EnsureCerts(); err != nil {
		return nil, fmt.Errorf("failed to generate certificates: %w", err)
	}

	// Load server TLS config
	serverCert, err := tls.LoadX509KeyPair(
		filepath.Join(testCertsDir, "cert.pem"),
		filepath.Join(testCertsDir, "key.pem"),
	)
	if err != nil {
		return nil, fmt.Errorf("failed to load server cert: %w", err)
	}

	serverTLSConfig := &tls.Config{
		Certificates: []tls.Certificate{serverCert},
		MinVersion:   tls.VersionTLS12,
	}

	// Load CA for client verification
	caCert, err := os.ReadFile(filepath.Join(testCertsDir, "ca.pem"))
	if err != nil {
		return nil, fmt.Errorf("failed to read CA cert: %w", err)
	}

	caPool := x509.NewCertPool()
	if !caPool.AppendCertsFromPEM(caCert) {
		return nil, fmt.Errorf("failed to parse CA cert")
	}

	clientTLSConfig := &tls.Config{
		RootCAs:    caPool,
		MinVersion: tls.VersionTLS12,
	}

	// Setup Docker client and router
	dockerClient, err := docker.NewClient([]string{e2eNetwork}, e2eBaseDomain)
	if err != nil {
		return nil, fmt.Errorf("failed to create docker client: %w", err)
	}

	router := proxy.NewRouter()

	// Discover backends
	ctx := context.Background()
	backends, err := dockerClient.DiscoverBackends(ctx)
	if err != nil {
		return nil, fmt.Errorf("failed to discover backends: %w", err)
	}

	for _, backend := range backends {
		router.AddBackend(backend)
	}

	statusConfig := &proxy.StatusConfig{
		Version:       "e2e-test",
		StartTime:     time.Now(),
		CertsDir:      testCertsDir,
		AutoGenerated: true,
		Networks:      []string{e2eNetwork},
		BaseDomain:    e2eBaseDomain,
		HTTPPort:      e2eHTTPPort,
		HTTPSPort:     e2eHTTPSPort,
	}

	handler := proxy.NewHandler(router, dockerClient, e2eDashboardHost, e2eBaseDomain, statusConfig, nil)

	// Create HTTP server (for redirect)
	httpServer := &http.Server{
		Addr:    fmt.Sprintf(":%d", e2eHTTPPort),
		Handler: &proxy.RedirectHandler{HTTPSPort: e2eHTTPSPort},
	}

	// Create HTTPS server
	httpsServer := &http.Server{
		Addr:      fmt.Sprintf(":%d", e2eHTTPSPort),
		Handler:   handler,
		TLSConfig: serverTLSConfig,
	}

	server := &e2eServer{
		handler:      handler,
		router:       router,
		dockerClient: dockerClient,
		httpServer:   httpServer,
		httpsServer:  httpsServer,
		tlsConfig:    serverTLSConfig,
		clientConfig: clientTLSConfig,
	}

	// Start servers
	go func() {
		if err := httpServer.ListenAndServe(); err != http.ErrServerClosed {
			fmt.Fprintf(os.Stderr, "HTTP server error: %v\n", err)
		}
	}()

	go func() {
		if err := httpsServer.ListenAndServeTLS("", ""); err != http.ErrServerClosed {
			fmt.Fprintf(os.Stderr, "HTTPS server error: %v\n", err)
		}
	}()

	// Wait for servers to be ready
	time.Sleep(500 * time.Millisecond)

	return server, nil
}

func (s *e2eServer) stop() {
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()

	s.httpServer.Shutdown(ctx)
	s.httpsServer.Shutdown(ctx)
	s.dockerClient.Close()
}

func (s *e2eServer) httpClient() *http.Client {
	return &http.Client{
		Transport: &http.Transport{
			TLSClientConfig: s.clientConfig,
			// Disable connection reuse for cleaner tests
			DisableKeepAlives: true,
		},
		Timeout: 10 * time.Second,
		// Don't follow redirects automatically
		CheckRedirect: func(req *http.Request, via []*http.Request) error {
			return http.ErrUseLastResponse
		},
	}
}

// resolveHost creates a dialer that resolves test hostnames to localhost
func resolveHost(port int) func(ctx context.Context, network, addr string) (net.Conn, error) {
	return func(ctx context.Context, network, addr string) (net.Conn, error) {
		// Replace any *.test.localhost with localhost:port
		if strings.HasSuffix(addr, ".test.localhost:"+fmt.Sprint(port)) ||
			strings.HasSuffix(addr, ".test.localhost") {
			addr = fmt.Sprintf("127.0.0.1:%d", port)
		}
		return (&net.Dialer{}).DialContext(ctx, network, addr)
	}
}

func (s *e2eServer) httpClientWithResolver() *http.Client {
	transport := &http.Transport{
		TLSClientConfig: s.clientConfig,
		DialContext:     resolveHost(e2eHTTPSPort),
	}
	return &http.Client{
		Transport: transport,
		Timeout:   10 * time.Second,
		CheckRedirect: func(req *http.Request, via []*http.Request) error {
			return http.ErrUseLastResponse
		},
	}
}

